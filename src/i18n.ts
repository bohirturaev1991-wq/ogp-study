export type Key = keyof typeof dict;

export function tr(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  let s: string = dict[key][lang];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function useT() {
  const lang = useStore((s) => s.profile.lang);
  return {
    lang,
    t: (key: Key, vars?: Record<string, string | number>) => tr(lang, key, vars),
    l: (v: L10n | undefined) => (v ? v[lang] || v.uz || v.ru : ''),
  };
}
